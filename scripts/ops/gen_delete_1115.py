#!/usr/bin/env python3
"""Generate the 11-15 delete scripts for hpg (user approval in the tc channel, 2026-11-15 06:28 CST:
"建议删除的都可以删" = items A, B, D of reports/analysis/hpg_delete_candidates_20261112_ZH.md).

usage: gen_delete_1115.py MANIFEST_DIR OUT_DIR AB|D [units.tsv]

Every removal in the generated scripts is a LITERAL absolute path (no variables, no globs), guarded by an
existence/type check; a /orange big file is removed only if its size equals the manifest size.
  AB -> tc_delete_AB.sh   : A on /orange (manifest rows under _trash / _failed / the two core dumps), A on /blue
                            (the _trash / _failed remainders), B (old-phase benchmark envs; 2a.13 is HELD OUT:
                            YD/tc-alignment/.venv is TRAIN_PYTHON of configs/hpg.env, found 11-15).
  D  -> tc_delete_D.sh + tc_delete_D.part{0..3}.sh : the 11 D directories on /blue (split over 4 streams by the
                            census file counts) + their 9 big files on /orange.
Also writes _DELETED_20261115.<key>.tsv (the manifest rows removed) per affected /orange root.
"""
import collections, os, re, shlex, sys

MAN, OUT, WHAT = sys.argv[1], sys.argv[2], sys.argv[3]
UNITS = sys.argv[4] if len(sys.argv) > 4 else None
os.makedirs(OUT, exist_ok=True)
O = "/orange/yd24f.fsu/xc25.fsu"
DEPT = "/blue/fsu-compsci-dept/xc25.fsu/hq"
YD = "/blue/yd24f.fsu/xc25.fsu/hq"
A_ = DEPT + "/ICML27_agent_distillation"
STAGE = O + "/tc-cold/_ops"
DATE = "20261115"
# key -> (orange DSTROOT, blue ROOT)
ROOTS = collections.OrderedDict([
    ("dept-ICML27_agent_distillation", (O + "/icml27-cold/blue-dept/ICML27_agent_distillation", A_)),
    ("dept-ICML27_v0_runs", (O + "/icml27-cold/blue-dept/ICML27_v0_runs", DEPT + "/ICML27_v0_runs")),
    ("dept-ICML27_runs", (O + "/icml27-cold/blue-dept/ICML27_runs", DEPT + "/ICML27_runs")),
    ("yd-_trash", (O + "/tc-cold/blue-yd24f/_trash", YD + "/_trash")),
])
D_REL = ["reports/smartad-selection/chain_k500_s0_r2_e2b", "reports/smartad-selection/chain_k500_s0_r2",
         "reports/smartad-selection/k100_s0", "reports/smartad-selection/k100_s1", "reports/smartad-selection/k100_s2",
         "reports/runs/smartad-collections/k100_s0", "reports/runs/smartad-collections/k100_s1", "reports/runs/smartad-collections/k100_s2",
         "reports/adftp-collections/k100_s0", "reports/adftp-collections/k100_s1", "reports/adftp-collections/k100_s2"]


def rows(key):
    dst = ROOTS[key][0]
    rel = os.path.relpath(dst, O)
    d = os.path.join(MAN, rel)
    out = []
    for fn in sorted(os.listdir(d)):
        if not fn.startswith("_tc_moved_big_files."):
            continue
        for line in open(os.path.join(d, fn)):
            if line.startswith("#") or not line.strip():
                continue
            sha, size, path = line.rstrip("\n").split("\t")
            assert not path.startswith("/") and ".." not in path.split("/") and "'" not in path and "\n" not in path, path
            out.append((sha, int(size), path, fn))
    return out


def q(p):
    s = shlex.quote(p)
    assert s.startswith("'") or re.fullmatch(r"[A-Za-z0-9_./-]+", s), p
    return s


HEAD = """#!/bin/bash
# GENERATED by scripts/ops/gen_delete_1115.py — %s. Runs ON hpg, detached. User approval: tc channel 2026-11-15
# 06:28 CST "建议删除的都可以删" (items A, B, D of hpg_delete_candidates_20261112_ZH.md). Every removal below is a
# literal absolute path. Stops at the first failure.
set -u
LOCK=/orange/yd24f.fsu/xc25.fsu/.orange_move.lock
exec 9>>"$LOCK" || { echo "FAIL: cannot open the move lock"; exit 3; }
flock -n 9 || { echo "BUSY: the /orange move lock is held by someone else — nothing deleted"; exit 3; }
quota() { echo "QUOTA $1 $(date '+%%F %%T %%Z')"
  echo "  blue uid   $(lfs quota -q -u xc25.fsu /blue/fsu-compsci-dept | tr -s ' ')"
  echo "  blue dept  $(lfs quota -q -p 2273 /blue/fsu-compsci-dept | tr -s ' ')"
  echo "  blue yd    $(lfs quota -q -p 2228 /blue/yd24f.fsu | tr -s ' ')"
  echo "  orange uid $(lfs quota -q -u xc25.fsu /orange/yd24f.fsu | tr -s ' ')"
  echo "  orange gid $(lfs quota -q -g yd24f.fsu /orange/yd24f.fsu | tr -s ' ')"; }
echo "$(date '+%%T') start host=$(hostname) pid=$$"
"""


def del_file(size, path):
    p = q(path)
    return (f"[ -f {p} ] && [ ! -L {p} ] && [ \"$(stat -c %s {p})\" = {size} ] && rm -f -- {p} && [ ! -e {p} ] "
            f"&& echo \"DEL {size} \"{p} || {{ echo \"FAILDEL \"{p}; exit 1; }}\n")


def del_dir(path, tag):
    p = q(path)
    assert path.startswith(DEPT + "/") or path.startswith(YD + "/"), path
    assert path.count("/") >= 6 and not path.endswith("/"), path
    return (f"if [ -L {p} ] || [ ! -d {p} ]; then echo \"FAILDEL not a real directory: \"{p}; exit 1; fi\n"
            f"n=$(rm -rf -v -- {p} | wc -l); [ ! -e {p} ] && echo \"$(date '+%T') DELDIR {tag} $n \"{p} || {{ echo \"FAILDEL \"{p}; exit 1; }}\n")


def deleted_tsv(key, rws, what):
    dst, root = ROOTS[key]
    fn = os.path.join(OUT, f"_DELETED_{DATE}.{what}.{key}.tsv")
    with open(fn, "w") as f:
        f.write(f"# rows of the _tc_moved_big_files.*.tsv manifests in {dst} whose files were DELETED on 2026-11-15 "
                f"(user approval in the tc channel, item {what}). They no longer exist on /orange or /blue: skip them in any restore.\n")
        f.write("# columns: sha256, bytes, relative path, manifest\n")
        for sha, size, path, man in rws:
            f.write(f"{sha}\t{size}\t{path}\t{man}\n")
    return fn


def place_tsv(key, what):
    dst, root = ROOTS[key]
    src = f"{STAGE}/delete_{DATE}/_DELETED_{DATE}.{what}.{key}.tsv"
    name = f"_DELETED_{DATE}.{what}.tsv"
    s = f"cp -- {q(src)} {q(dst + '/' + name)} && echo \"NOTE {q(dst + '/' + name)}\" || {{ echo \"FAIL: could not write the deleted-rows note in {dst}\"; exit 1; }}\n"
    s += f"if [ -d {q(root)} ]; then cp -- {q(src)} {q(root + '/' + name)} && echo \"NOTE {q(root + '/' + name)}\"; fi\n"
    return s


if WHAT == "AB":
    sel = collections.OrderedDict()
    sel["dept-ICML27_agent_distillation"] = [r for r in rows("dept-ICML27_agent_distillation") if r[2].startswith("_trash/")]
    sel["dept-ICML27_v0_runs"] = [r for r in rows("dept-ICML27_v0_runs") if r[2].startswith("_failed/")]
    sel["dept-ICML27_runs"] = rows("dept-ICML27_runs")
    sel["yd-_trash"] = rows("yd-_trash")
    assert all(re.fullmatch(r"[0-9a-f]{7}/core\.pt_nccl_watchdg-[^/]+", r[2]) for r in sel["dept-ICML27_runs"]), sel["dept-ICML27_runs"]
    assert all(r[2].startswith("ICML27_agent_distillation/superseded_1007/") for r in sel["yd-_trash"])
    n = sum(len(v) for v in sel.values()); b = sum(r[1] for v in sel.values() for r in v)
    print("A on /orange:", {k: (len(v), sum(r[1] for r in v)) for k, v in sel.items()}, "total", n, b)
    # Section 1 of the candidate list says 222 files / 1,376,823,029,813 B. Two of those (153,967,410 B) are
    # v0_k20_r1/_failed/label-bytecap-96605d3/{label/rows.json,dataset/examples.jsonl}: a _failed dir INSIDE the live
    # v0_k20_r1 run, not under ICML27_v0_runs/_failed/ as row 1.4 describes -> NOT deleted (kept on /orange).
    assert (n, b) == (220, 1376823029813 - 153967410), (n, b)
    s = HEAD % "A + B"
    s += "quota before\n"
    s += "echo \"== A on /orange: %d manifest-listed files, %d bytes\"\n" % (n, b)
    for key, rws in sel.items():
        for sha, size, path, man in rws:
            s += del_file(size, ROOTS[key][0] + "/" + path)
        deleted_tsv(key, rws, "A")
    # empty directory skeletons left behind under the three _trash / _failed roots on /orange (directories only)
    for d in (ROOTS["dept-ICML27_agent_distillation"][0] + "/_trash", ROOTS["dept-ICML27_v0_runs"][0] + "/_failed",
              ROOTS["yd-_trash"][0] + "/ICML27_agent_distillation"):
        s += f"if [ -d {q(d)} ] && [ ! -L {q(d)} ]; then find {q(d)} -depth -type d -empty -delete; [ -e {q(d)} ] && echo \"KEPT non-empty: $(find {q(d)} -type f | wc -l) files under \"{q(d)} || echo \"RMDIR-EMPTY \"{q(d)}; fi\n"
    for key in sel:
        s += place_tsv(key, "A")
    s += "quota after-A-orange\n"
    s += "echo \"== A on /blue: the _trash / _failed remainders\"\n"
    # children of DEPT/ICML27_agent_distillation/_trash as listed by tc_del_precheck.sh on 11-15 (28 directories)
    trash_children = """derive_k50_test_1020 e2b-smc-k30-e32-lr1e-4-eval-bf16ref-1025 e4b-adc-k100-e64-lr1e-4-s2.partial.1792996795
        e4b-smc-k100-e64-lr1e-4-s2-eval-bf16ref-10282341 e4b-smc-k10-e32-lr1e-4-eval-bf16ref-1025b
        e4b-smc-k10-e32-lr1e-4-s2-eval-bf16ref-10271531 e4b-smc-k20-e32-lr1e-4-eval-bf16ref-1025b
        e4b-smc-k20-e32-lr1e-4-s2-eval-bf16ref-10282100 e4b-smc-k30-e32-lr1e-4-eval-bf16ref-1025
        e4b-smc-k30-e32-lr1e-4-s1-eval-bf16ref-1025 e4b-smc-k30-e32-lr1e-4-s2-eval-bf16ref-1025 es_eval_fa2_1025
        eval_reset_error_1022 leap_60s_timeout_1019 partial_tree_89f57a2_1019 partial_trees_1024
        r03_r2_A1_n100_timeout_20261013 sad_identity_95a62b2_1025 sad_k100_nomask_1025
        smc-k30-e32-lr1e-4-eval-bf16ref-1023 smc-k30-e32-lr1e-4-eval-fp32ref-1023 smc_prep_4gpu_1023
        smc_prep_4gpu_1023b smc_prep_4gpu_1023c tainted_or_failed_1019 variants_pre_eseries_1024""".split()
    assert len(trash_children) == 26, len(trash_children)
    for c in trash_children:
        s += del_dir(A_ + "/_trash/" + c, "A-blue")
    s += del_dir(A_ + "/_trash", "A-blue")
    s += del_dir(DEPT + "/ICML27_v0_runs/_failed", "A-blue")
    s += del_dir(YD + "/_trash/ICML27_agent_distillation/superseded_1007", "A-blue")
    s += "quota after-A-blue\n"
    s += "echo \"== B: old-phase benchmark environments (2a.13 YD/tc-alignment/.venv held out)\"\n"
    for c in ["bfcl", "bfcl-venv", "tau2", "tau-bench", "appworld-data", "appworld-official", "appworld-repo", "appworld-venv",
              "appworld-data-downloaded", "ds1000", "bird", ".python"]:
        s += del_dir(DEPT + "/tc-alignment/envs/" + c, "B")
    s += del_dir(YD + "/tc-alignment/envs", "B")
    s += "quota after-B\n"
    s += "echo \"$(date '+%T') DELETE_AB_DONE\"\n"
    open(os.path.join(OUT, "tc_delete_AB.sh"), "w").write(s)
    print("wrote", os.path.join(OUT, "tc_delete_AB.sh"), s.count("rm -f --"), "file removals,", s.count("rm -rf -v --"), "directory removals")

elif WHAT == "D":
    dre = re.compile(r"^(%s)/" % "|".join(re.escape(d) for d in D_REL))
    rws = [r for r in rows("dept-ICML27_agent_distillation") if dre.match(r[2])]
    print("D on /orange:", len(rws), sum(r[1] for r in rws))
    for r in rws:
        print("   ", r[1], r[2])
    assert len(rws) == 9, len(rws)
    deleted_tsv("dept-ICML27_agent_distillation", rws, "D")
    # split the 11 directories over 4 streams by census file counts; children come from the listing file given as argv[4]:
    # lines "<files>\t<absolute child dir>" for the children of each D dir (made on hpg right before generating)
    kids = []
    for line in open(UNITS):
        n, p = line.rstrip("\n").split("\t")
        assert any(p.startswith(A_ + "/" + d + "/") for d in D_REL) and "'" not in p and ".." not in p.split("/"), p
        kids.append((int(n), p))
    kids.sort(reverse=True)
    parts = [[] for _ in range(4)]; load = [0] * 4
    for n, p in kids:
        i = load.index(min(load)); parts[i].append(p); load[i] += n
    print("streams (entries by listing):", load)
    for i, ps in enumerate(parts):
        s = "#!/bin/bash\n# GENERATED part %d of tc_delete_D.sh — literal absolute paths only.\nset -u\n" % i
        for p in ps:
            s += del_dir(p, "D-part%d" % i)
        s += "echo \"$(date '+%%T') PART_DONE %d\"\n" % i
        open(os.path.join(OUT, "tc_delete_D.part%d.sh" % i), "w").write(s)
    s = HEAD % "D"
    s += "quota before\n"
    s += "echo \"== D on /orange: 9 manifest-listed files\"\n"
    for sha, size, path, man in rws:
        s += del_file(size, ROOTS["dept-ICML27_agent_distillation"][0] + "/" + path)
    for d in D_REL[:5]:
        dd = ROOTS["dept-ICML27_agent_distillation"][0] + "/" + d
        s += f"if [ -d {q(dd)} ] && [ ! -L {q(dd)} ]; then find {q(dd)} -depth -type d -empty -delete; [ -e {q(dd)} ] && echo \"KEPT non-empty: \"{q(dd)} || echo \"RMDIR-EMPTY \"{q(dd)}; fi\n"
    s += place_tsv("dept-ICML27_agent_distillation", "D")
    s += "echo \"== D on /blue: 4 streams\"\n"
    for i in range(4):
        s += f"bash {q(STAGE + '/delete_' + DATE + '/tc_delete_D.part%d.sh' % i)} > {q(STAGE + '/logs/delete_D.part%d.' % i + DATE + '.log')} 2>&1 &\n"
    s += "wait\n"
    for i in range(4):
        lg = q(STAGE + '/logs/delete_D.part%d.' % i + DATE + '.log')
        s += f"grep -q '^[0-9:]* PART_DONE {i}$' {lg} && ! grep -q '^FAILDEL' {lg} || {{ echo \"FAIL: part {i} did not finish cleanly, see \"{lg}; exit 1; }}\n"
    s += "echo \"== D on /blue: the directories themselves\"\n"
    for d in D_REL:
        s += del_dir(A_ + "/" + d, "D")
    s += "quota after-D\n"
    s += "echo \"$(date '+%T') DELETE_D_DONE\"\n"
    open(os.path.join(OUT, "tc_delete_D.sh"), "w").write(s)
    print("wrote", os.path.join(OUT, "tc_delete_D.sh"))
else:
    sys.exit("AB or D")
