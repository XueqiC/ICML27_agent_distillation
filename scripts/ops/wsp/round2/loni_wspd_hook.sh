#!/bin/bash
# loni_wspd_hook.sh — runs ON LONI, called by the pass script (queue/hooks/). D lane of round 2 on LONI (C4 / D3 / D4 / W3):
# (1) submits the family jobs once their code / inputs are in place (resubmits a failed family at most 3 times);
# (2) submits one merged-checkpoint evaluation job per finished export; (3) prints family states and collected numbers.
W=/work/xueqic/hq; D=/work/xueqic/hq/ICML27_wsp_d; Q=/work/xueqic/hq/ICML27_wsp/queue; S=$Q/tc_wsp_submit_loni.sh
inq() { squeue -u $USER -h -o %j | grep -q -x -F "$1"; }
nsub() { cut -f1 $Q/submitted.tsv | grep -c -x -F "$1"; }
files=$(lfs quota -u $USER /work 2>/dev/null | grep -E '^ +/work' | awk '{print $6}' | tr -d '*'); files=${files:-0}
if [ "$files" -le 3750000 ]; then
  for fam in $(cat $D/scripts/families.enabled 2>/dev/null); do
    case $fam in c4) lim=04:00:00;; *) lim=12:00:00;; esac
    [ -f "$Q/derive/d_$fam.sh" ] && [ ! -f "$Q/done/d.$fam" ] && ! inq wsp-gpu-d_$fam && [ "$(nsub gpucmd:d_$fam.sh)" -lt 3 ] && bash $S gpucmd d_$fam.sh 16 $lim
  done
  for m in $D/export_*/*/surgery_manifest.json; do [ -f "$m" ] || continue
    e=$(dirname "$m"); cond=$(basename "$e"); fam=$(basename "$(dirname "$e")"); fam=${fam#export_}; name="$fam-$cond"; scr="dev_$name.sh"
    [ "$(nsub gpucmd:$scr)" -ge 1 ] && continue
    runs=1; lim=00:55:00
    case "$cond" in B0|B1) runs=2; lim=01:20:00;; esac
    if [ -f "$D/conditions_$fam/selection.json" ] && [ "${cond#C4_a}" != "$cond" ] && python3 -c 'import json,sys; sys.exit(0 if format(json.load(open(sys.argv[1]))["chosen_alpha"], "g") == sys.argv[2] else 1)' "$D/conditions_$fam/selection.json" "${cond#C4_a}"; then runs=2; lim=01:20:00; fi
    printf '#!/bin/bash\n# generated by loni_wspd_hook.sh: merged-checkpoint evaluation of %s\nexport MERGED_MODEL_PATH=%s NAME=%s DEV140_RUNS=%s\nexec bash %s/scripts/loni_wspd_merged_eval.sh\n' "$name" "$e" "$name" "$runs" "$D" > "$Q/derive/$scr"
    bash $S gpucmd "$scr" 16 $lim
  done
fi
echo "== D lane (LONI): families"; for fam in c4 d3 d4 d5; do f=$(ls -t $Q/logs/slurm-wsp-gpu-d_$fam-*.out 2>/dev/null | head -1); [ -n "$f" ] && echo "-- $fam: $(grep -E '^== ' "$f" | tail -n 1 | cut -c1-140) | $(grep -E 'D_[A-Z0-9]+_(DONE|FAIL)' "$f" | tail -n 1)"; done
echo "== D lane: exports $(ls -d $D/export_*/*/surgery_manifest.json 2>/dev/null | wc -l); results (t2 of 20 [progress] | dev140)"
for s in $D/eval/*.merged.*/eval/summary.json; do [ -f "$s" ] || continue
  python3 - "$s" <<'PY'
import json, os, sys
p = sys.argv[1]; j = json.load(open(p)); n = j.get("episodes"); s = j.get("successes")
if s is None and j.get("success_rate") is not None and n: s = round(j["success_rate"] * n)
g = os.path.join(os.path.dirname(p), "progress.json"); extra = ""
if os.path.isfile(g): extra = " progress %.4f" % json.load(open(g))["mean_progress"]
print("%-36s %s/%s err=%s%s" % (p.split("/")[-3], s, n, j.get("error_episodes"), extra))
PY
done
